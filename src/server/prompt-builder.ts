export type CardParams = {
  title: string;
  description?: string;
};

export const buildPrompt = (params: CardParams) => `
あなたはトレーディングカードゲームのデザイナーです。
提供された画像と、ユーザーからの入力情報をもとに、ユニークで面白いトレーディングカードのデータを生成してください。

## 入力情報
- タイトル: ${params.title}
- 画像の説明: ${params.description || "なし"}

## 生成ルール
1. **レアリティ (1-10)**: 画像の「貴重さ」や「インパクト」に基づいて決定してください。
   - ★1-3: 日常的、ありふれたもの（例：ラーメン、道端の石）
   - ★4-7: ちょっと珍しい、面白い瞬間
   - ★8-10: 人生の重大イベント、奇跡的な瞬間（例：結婚式、UFO）

2. **ステータス**: レアリティに比例させてください。
   - 攻撃力/守備力: 0 〜 5000

3. **属性と種族**: 画像の雰囲気から適当に決定してください。
   - 属性例: 炎、水、風、地、光、闇、神、無
   - 種族例: 人間、ドラゴン、機械、料理、風景、動物、アンデット

4. **フレーバーテキスト**:
   - 画像の状況を、**過剰にドラマチック**、あるいは**シュール**に表現してください。
   - TCG特有の壮大な言い回し（「太古より伝わりし...」）や、意味深なポエムを使ってください。
   - ユーザーの「画像の説明」があれば、それを元に飛躍させてください。

5. **効果**: なし（バニラカードとして扱います）

## 出力フォーマット
以下のJSON形式のみを出力してください。Markdownのコードブロックは不要です。

{
  "name": "カード名（タイトルを元にTCGっぽくアレンジ）",
  "rarity": 1, // 1-10の整数
  "attribute": "属性",
  "type": "種族",
  "attack": 100,
  "defense": 100,
  "flavorText": "フレーバーテキスト"
}
`;
